<?php

use App\Models\Account;
use App\Models\User;

test('login screen can be rendered', function () {
    $response = $this->get('/login');

    $response->assertStatus(200);
});

test('users can authenticate using the login screen', function () {
    $user = User::factory()->create();

    $response = $this->post('/login', [
        'email' => $user->email,
        'password' => 'password',
    ]);

    $this->assertAuthenticated();
    $response->assertRedirect(route('dashboard', absolute: false));
});

test('users can not authenticate with invalid password', function () {
    $user = User::factory()->create();

    $this->post('/login', [
        'email' => $user->email,
        'password' => 'wrong-password',
    ]);

    $this->assertGuest();
});

test('users can logout', function () {
    $user = User::factory()->create();

    $response = $this->actingAs($user)->post('/logout');

    $this->assertGuest();
    $response->assertRedirect('/');
});


test('legacy client users are redirected to the client portal after login', function () {
    $account = Account::query()->create([
        'name' => 'Legacy Login Client',
        'code' => 'CLIENT-LOGIN',
        'account_type' => Account::TYPE_CUSTOMER,
        'is_active' => true,
    ]);

    $user = User::factory()->create([
        'account_id' => $account->id,
        'account_type' => 'client',
        'is_active' => true,
    ]);

    $response = $this->post('/login', [
        'email' => $user->email,
        'password' => 'password',
    ]);

    $this->assertAuthenticatedAs($user);
    $response->assertRedirect(route('client.dashboard', absolute: false));
});
